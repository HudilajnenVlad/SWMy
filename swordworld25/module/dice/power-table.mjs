/** Highest power value available in the table. */
export const MAX_POWER = POWER_TABLE.length - 1;

/**
 * Look up the power table.
 * @param {number} power   Power value (clamped to 0..100)
 * @param {number} result  2d result (values above 12 are treated as 12)
 * @returns {number|null} Damage, or null for an automatic failure (a result of 2 or less)
 */
export function lookupPower(power, result) {
  if ( result <= 2 ) return null;
  const p = Math.clamp(Math.round(Number(power) || 0), 0, MAX_POWER);
  const r = Math.clamp(Math.round(result), 3, 12);
  return POWER_TABLE[p][r - 3];
}
